'''
KOOK 类型定义模块：集中管理消息类型、频道类型、静音类型等枚举，供库内各模块与调用方统一使用。
'''
from enum import IntEnum, IntFlag, StrEnum      # 提供整型/组合标志/字符串枚举基类，用于定义固定取值集合


class 消息类型(IntEnum):
    """KOOK 消息/事件类型编号。发送消息时 type 传这些值，事件推送时 d.type 也是这些值。"""
    纯文本 = 1                                # 纯文本消息
    图片 = 2                                  # 图片消息(content 为图片 url)
    视频 = 3                                  # 视频消息
    文件 = 4                                  # 文件消息
    音频 = 8                                  # 音频消息
    KMD文本 = 9                               # KMarkdown 富文本消息，频道消息发送默认类型
    卡片 = 10                                 # 卡片消息(content 为卡片 JSON 字符串)
    系统 = 255                                # 系统事件(需再读 extra.type 区分具体事件)


class 频道类型(IntEnum):
    """KOOK 频道类型编号。"""
    分组 = 0                                  # 分组频道(仅用于分类展示)
    文字 = 1                                  # 文字频道
    语音 = 2                                  # 语音频道


class 静音类型(IntEnum):
    """KOOK 服务器静音接口的静音方式编号。"""
    麦克风闭麦 = 1                             # 闭麦(关闭麦克风)
    耳机静音 = 2                               # 静音(关闭收听)


class 系统事件名(StrEnum):
    """系统事件(消息 type=255)中 extra.type 的具体事件名，取护航业务常用的一部分。"""
    按钮点击 = "message_btn_click"             # 卡片消息中按钮被点击，extra.body 含 value/user_id/msg_id/target_id
    用户加入语音频道 = "joined_channel"         # 用户加入语音频道
    用户退出语音频道 = "exited_channel"         # 用户退出语音频道
    用户信息更新 = "user_updated"              # 用户用户名或头像变更
    自己加入服务器 = "self_joined_guild"        # 机器人被邀请/主动加入服务器
    自己退出服务器 = "self_exited_guild"        # 机器人被踢/拉黑/主动退出服务器


class 服务器权限(IntFlag):
    """
    KOOK 服务器/频道权限位(比特位 0-30，可组合)。
    组合用法: int(服务器权限.管理消息 | 服务器权限.踢出用户)。
    拥有"管理员"时忽略其余位全部放行；比特位定义来自官方角色权限文档。
    """
    管理员 = 1                     # 0: 完整管理权(危险，绕过全部权限限制)
    管理服务器 = 1 << 1            # 1: 修改服务器名称与区域
    查看管理日志 = 1 << 2          # 2: 查看服务器管理日志
    创建服务器邀请 = 1 << 3        # 3: 创建服务器邀请链接
    管理邀请 = 1 << 4              # 4: 管理服务器邀请
    频道管理 = 1 << 5              # 5: 创建/编辑/删除频道
    踢出用户 = 1 << 6              # 6: 把成员踢出服务器
    封禁用户 = 1 << 7              # 7: 封禁服务器成员
    管理自定义表情 = 1 << 8         # 8: 管理服务器自定义表情
    修改服务器昵称 = 1 << 9         # 9: 更改自己的服务器昵称
    管理角色权限 = 1 << 10          # 10: 创建/编辑/删除低于自身的角色
    查看文字语音频道 = 1 << 11      # 11: 查看文字与语音频道
    发布消息 = 1 << 12             # 12: 在频道中发布消息
    管理消息 = 1 << 13             # 13: 删除他人消息与置顶消息
    上传文件 = 1 << 14             # 14: 上传文件
    连接语音 = 1 << 15             # 15: 连接语音频道
    语音管理 = 1 << 16             # 16: 移动/踢出语音频道成员
    提及全体成员 = 1 << 17          # 17: 使用 @全体成员
    添加反应 = 1 << 18             # 18: 对消息添加新反应
    跟随添加反应 = 1 << 19          # 19: 跟随使用已添加的反应
    被动连接语音 = 1 << 20          # 20: 限制位，不能主动连接语音频道
    仅使用按键说话 = 1 << 21        # 21: 限制位，语音中只能按键说话
    使用自由麦 = 1 << 22           # 22: 语音中可自由说话
    说话 = 1 << 23                 # 23: 在语音频道中说话
    服务器静音 = 1 << 24            # 24: 对成员使用服务器静音
    服务器闭麦 = 1 << 25            # 25: 对成员使用服务器闭麦
    修改他人昵称 = 1 << 26          # 26: 更改他人的服务器昵称
    播放伴奏 = 1 << 27             # 27: 在语音频道播放音乐伴奏
    屏幕分享 = 1 << 28             # 28: 分享屏幕
    回复帖子 = 1 << 29             # 29: 在帖子频道回复
    开启录音 = 1 << 30             # 30: 在语音频道开启录音
