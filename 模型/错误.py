'''
KOOK 错误定义模块：集中定义库内使用的异常类型。
'''


class 接口错误(Exception):
    """KOOK HTTP 接口返回业务错误时抛出，携带服务端错误码与说明。"""

    def __init__(self, 状态码: int, 消息: str, 接口: str):
        """
        记录错误信息。
        参数:
            状态码: KOOK 返回的 code，0 代表成功，非 0 代表业务错误。
            消息: KOOK 返回的错误说明文本。
            接口: 出错的接口路径，便于排查。
        """
        self.状态码 = 状态码
        self.接口 = 接口
        super().__init__(f"接口 {接口} 失败: code={状态码} message={消息}")


class 令牌错误(Exception):
    """网关握手时发现令牌缺失/无效/过期等不可恢复的鉴权问题。"""
